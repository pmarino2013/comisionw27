let base, altura, area;

base = parseFloat(prompt("Ingrese la base del cuadrilatero: "));
altura = parseFloat(prompt("Ingrese la altura del cuadrilatero: "));
area = base * altura;

document.write(`El area del cuadrilatero de base ${base} y altura ${altura} es: ${area}`);
console.log(`El area del cuadrilatero de base ${base} y altura ${altura} es: ${area}`);